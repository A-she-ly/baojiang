def get_translation(word: str) -> str:
    """Get Chinese translation for a Spanish word."""
    # Try exact match first
    if word in SPANISH_CHINESE_DICT:
        return SPANISH_CHINESE_DICT[word]
    
    # Try lowercase
    lower = word.lower()
    if lower in SPANISH_CHINESE_DICT:
        return SPANISH_CHINESE_DICT[lower]
    
    # Return the word itself as fallback (will be shown untranslated)
    return word


